import assert from 'node:assert/strict';
import {World} from './physics.mjs';
const dt=1/120;
const w=new World();
w.add(7,120,250);w.add(7,120,250);w.step(dt);
assert.equal(w.bossProduced,1);assert.equal(w.balls.filter(b=>b.kind==='kamilla').length,1);
w.add(7,280,580);w.add(7,280,580);w.step(dt);
assert.equal(w.bossProduced,2);assert.equal(w.balls.filter(b=>b.kind==='demir').length,1);
assert(!w.bond,'duo should not merge without physical touching');
w.add(7,170,460);w.add(7,170,460);w.step(dt);
assert.equal(w.bossProduced,3);assert(w.murUntil>w.time);assert.equal(w.balls.filter(b=>b.level===8).length,2);
